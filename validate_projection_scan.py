#!/usr/bin/env python3
"""
Validate a projection-crossing scan at higher curve resolution.

Inputs:
    XYZ-like centerline coordinates and a CSV generated by
    analyze_projection_crossings.py.
Output:
    A text report comparing selected CSV directions against crossing counts
    recomputed with the full-resolution curve.  Optionally, the script also
    performs a separate coarse spherical search for a lower crossing count.

This mirrors the validation used for sc_W3_ALocal.xyz: a 1000-point scan can be
checked on the original 2000-point centerline, while an independent large
coarse scan tests whether a small orientation region with fewer crossings was
missed.

Example:
    python validate_projection_scan.py examples/sc_W3_ALocal.xyz \
        examples/sc_W3_ALocal_projection_scan.csv --n-check 500 --seed 2026

Optional coarse search:
    python validate_projection_scan.py examples/sc_W3_ALocal.xyz \
        examples/sc_W3_ALocal_projection_scan.csv \
        --n-check 500 --extra-directions 40000 --coarse-points 500

Run without arguments, or with --gui, to enter the parameters in a window.

Python 3.9+; requires NumPy.  Shapely 2.x is recommended for speed.
"""

import argparse
import csv
import os
import sys
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from analyze_projection_crossings import (
    HAVE_SHAPELY,
    count_projection_crossings,
    fibonacci_sphere,
    read_xyz,
    resample_closed_polyline,
    strip_closing_duplicate,
)

try:
    from writhe_gui import add_gui_argument, gui_requested, launch_gui
except ModuleNotFoundError as exc:  # the command line works without the GUI module
    if exc.name != "writhe_gui":
        raise

    def add_gui_argument(parser: argparse.ArgumentParser) -> None:
        """writhe_gui.py is missing, so there is no --gui option."""

    def gui_requested(argv: Sequence[str]) -> bool:
        return False

    launch_gui = None


def add_suffix(path: str, suffix: str, ext: str) -> str:
    root, _old = os.path.splitext(path)
    return root + suffix + ext


def read_scan_csv(path: str) -> Dict[str, np.ndarray]:
    labels: List[str] = []
    directions: List[List[float]] = []
    unsigned: List[int] = []
    signed: List[int] = []
    with open(path, "r", encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            labels.append(row["label"])
            directions.append([float(row["nx"]), float(row["ny"]), float(row["nz"])])
            unsigned.append(int(row["unsigned_crossings"]))
            signed.append(int(row["signed_crossing_sum"]))
    if not labels:
        raise ValueError("Scan CSV contains no rows.")
    return {
        "labels": np.asarray(labels, dtype=object),
        "directions": np.asarray(directions, dtype=float),
        "unsigned": np.asarray(unsigned, dtype=int),
        "signed": np.asarray(signed, dtype=int),
    }


def select_scan_rows(data: Dict[str, np.ndarray]) -> np.ndarray:
    labels = data["labels"]
    fib = np.array([str(x).startswith("fib_") for x in labels], dtype=bool)
    return np.where(fib if np.any(fib) else np.ones(len(labels), dtype=bool))[0]


def validate_rows(
    points_full: np.ndarray,
    data: Dict[str, np.ndarray],
    n_check: int,
    seed: int,
    engine: str,
) -> Tuple[int, List[str]]:
    """Recompute a random subset of scan directions at full resolution."""
    indices = select_scan_rows(data)
    rng = np.random.default_rng(seed)
    if n_check < len(indices):
        indices = np.sort(rng.choice(indices, size=n_check, replace=False))

    mismatches: List[str] = []
    for count, idx in enumerate(indices, start=1):
        n = data["directions"][idx]
        u, s, _ = count_projection_crossings(points_full, n, engine=engine)
        u0 = int(data["unsigned"][idx])
        s0 = int(data["signed"][idx])
        if u != u0 or s != s0:
            mismatches.append(
                "{}: CSV ({},{}) vs full ({},{}) at n=({:.6f},{:.6f},{:.6f})".format(
                    data["labels"][idx], u0, s0, u, s, n[0], n[1], n[2]
                )
            )
    return len(indices), mismatches


def coarse_minimum_search(
    points: np.ndarray,
    n_directions: int,
    engine: str,
    progress_every: int,
) -> Tuple[int, np.ndarray, int]:
    """Return minimum unsigned crossings, one attaining direction, and signed sum."""
    directions = fibonacci_sphere(n_directions)
    best_u = None
    best_n = None
    best_s = None
    for i, n in enumerate(directions):
        u, s, _ = count_projection_crossings(points, n, engine=engine)
        if best_u is None or u < best_u:
            best_u = u
            best_n = n.copy()
            best_s = s
        if progress_every and ((i + 1) % progress_every == 0 or i + 1 == n_directions):
            print("[INFO] coarse search {}/{}; current minimum={}".format(i + 1, n_directions, best_u))
    if best_u is None or best_n is None or best_s is None:
        raise RuntimeError("No directions were analyzed.")
    return int(best_u), best_n, int(best_s)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Validate a projection crossing scan against higher-resolution coordinates.")
    parser.add_argument("xyz_file", help="Input XYZ-like centerline")
    parser.add_argument("scan_csv", help="CSV from analyze_projection_crossings.py")
    parser.add_argument("--n-check", type=int, default=500, help="Number of scan directions to recheck at full resolution (default: 500)")
    parser.add_argument("--seed", type=int, default=2026, help="Random seed for selecting validation directions")
    parser.add_argument("--engine", choices=["auto", "shapely", "numpy"], default="auto", help="Crossing engine (default: auto)")
    parser.add_argument("--extra-directions", type=int, default=0, help="Optional independent coarse spherical search size; 0 disables")
    parser.add_argument("--coarse-points", type=int, default=500, help="Curve points for optional coarse search (default: 500)")
    parser.add_argument("--progress-every", type=int, default=1000, help="Progress interval for optional coarse search")
    parser.add_argument("--output", help="Output text report; default adds _validation.txt to scan CSV stem")
    add_gui_argument(parser)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> None:
    argv = list(sys.argv[1:] if argv is None else argv)
    if gui_requested(argv):
        sys.exit(launch_gui(build_parser, __file__, argv))
    parser = build_parser()
    args = parser.parse_args(argv)
    if getattr(args, "gui", False):  # an abbreviation of --gui, such as --gu
        sys.exit(launch_gui(build_parser, __file__, argv))
    if args.engine == "shapely" and not HAVE_SHAPELY:
        parser.error("--engine shapely requested, but Shapely is not installed")
    points_full = strip_closing_duplicate(read_xyz(args.xyz_file))
    data = read_scan_csv(args.scan_csv)

    n_checked, mismatches = validate_rows(
        points_full, data, args.n_check, args.seed, args.engine
    )

    extra_result = None
    if args.extra_directions > 0:
        coarse = resample_closed_polyline(points_full, args.coarse_points)
        extra_result = coarse_minimum_search(
            coarse, args.extra_directions, args.engine, args.progress_every
        )

    out = args.output or add_suffix(args.scan_csv, "_validation", ".txt")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("Projection-scan validation\n")
        handle.write("==========================\n")
        handle.write("XYZ: {}\n".format(args.xyz_file))
        handle.write("Scan CSV: {}\n".format(args.scan_csv))
        handle.write("Full-resolution points: {}\n".format(len(points_full)))
        handle.write("Directions rechecked: {}\n".format(n_checked))
        handle.write("Mismatches: {}\n".format(len(mismatches)))
        if mismatches:
            handle.write("\nMismatch details:\n")
            for line in mismatches:
                handle.write("  " + line + "\n")
        if extra_result is not None:
            best_u, best_n, best_s = extra_result
            handle.write("\nIndependent coarse search:\n")
            handle.write("  directions: {}\n".format(args.extra_directions))
            handle.write("  coarse curve points: {}\n".format(args.coarse_points))
            handle.write("  minimum unsigned crossings: {}\n".format(best_u))
            handle.write("  signed sum at example minimum: {}\n".format(best_s))
            handle.write(
                "  example normal: ({:.8f}, {:.8f}, {:.8f})\n".format(
                    best_n[0], best_n[1], best_n[2]
                )
            )

    print("[INFO] Validation report: {}".format(out))
    print("[INFO] Rechecked {} directions; mismatches={}".format(n_checked, len(mismatches)))


if __name__ == "__main__":
    main()
